#!/usr/bin/env node
// Generates docs/04-node-by-node.md from the built workflows, so the node
// reference cannot drift from what actually runs.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'n8n/workflows');

const TYPE_LABEL = {
  'n8n-nodes-base.scheduleTrigger': 'Schedule Trigger',
  'n8n-nodes-base.manualTrigger': 'Manual Trigger',
  'n8n-nodes-base.webhook': 'Webhook',
  'n8n-nodes-base.executeWorkflowTrigger': 'Execute Workflow Trigger',
  'n8n-nodes-base.executeWorkflow': 'Execute Workflow',
  'n8n-nodes-base.httpRequest': 'HTTP Request',
  'n8n-nodes-base.code': 'Code',
  'n8n-nodes-base.if': 'IF',
  'n8n-nodes-base.switch': 'Switch',
  'n8n-nodes-base.splitInBatches': 'Loop Over Items',
  'n8n-nodes-base.noOp': 'No Op',
  'n8n-nodes-base.respondToWebhook': 'Respond to Webhook',
  'n8n-nodes-base.merge': 'Merge',
  'n8n-nodes-base.set': 'Set'
};

/** What a node actually talks to, for the reference table. */
function target(node) {
  if (node.type === 'n8n-nodes-base.httpRequest') {
    const url = String(node.parameters?.url ?? '');
    if (url.includes('/rest/v1/rpc/')) return `db: \`${url.split('/rest/v1/rpc/')[1].split('?')[0]}()\``;
    if (url.includes('/rest/v1/')) return `db: \`${node.parameters.method} ${url.split('/rest/v1/')[1].split('?')[0]}\``;
    if (url.includes('api.anthropic.com')) return 'Claude (Messages API)';
    if (url.includes('apify.com')) return 'Apify';
    if (url.includes('apollo.io')) return 'Apollo';
    if (url.includes('graph.facebook.com')) return 'Instagram Graph API';
    if (url.includes('sheets.googleapis.com')) return 'Google Sheets';
    if (url.includes('OPERATOR_WEBHOOK_URL')) return 'operator notification (optional)';
    return 'HTTP';
  }
  if (node.type === 'n8n-nodes-base.webhook') return `\`${node.parameters.httpMethod} /webhook/${node.parameters.path}\``;
  if (node.type === 'n8n-nodes-base.scheduleTrigger') return `cron \`${node.parameters.rule.interval[0].expression}\``;
  if (node.type === 'n8n-nodes-base.executeWorkflow') return `runs \`${node.parameters.workflowId?.value}\``;
  if (node.type === 'n8n-nodes-base.code') {
    const libs = [...new Set((node.parameters.jsCode.match(/---- (lib\/[a-z-]+\.js)/g) ?? []).map((m) => m.replace('---- ', '')))];
    return libs.length ? `inlines ${libs.map((l) => `\`${l}\``).join(', ')}` : 'inline logic';
  }
  return '';
}

function flow(wf) {
  const lines = [];
  for (const [from, outputs] of Object.entries(wf.connections)) {
    const branches = outputs.main ?? [];
    branches.forEach((branch, index) => {
      for (const link of branch ?? []) {
        const label = branches.length > 1 ? ` (output ${index}${index === branches.length - 1 && wf.nodes.find((n) => n.name === from)?.onError === 'continueErrorOutput' ? ', error' : ''})` : '';
        lines.push(`${from}${label} -> ${link.node}`);
      }
    });
  }
  return lines;
}

const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
const sections = [];

for (const file of files) {
  const wf = JSON.parse(readFileSync(join(DIR, file), 'utf8'));
  const rows = wf.nodes.map((node) => {
    const flags = [
      node.retryOnFail ? `retry x${node.maxTries}` : null,
      node.onError === 'continueErrorOutput' ? 'error output' : null,
      node.onError === 'continueRegularOutput' ? 'continues on fail' : null
    ].filter(Boolean).join(', ');
    const note = (node.notes ?? '').replace(/\s+/g, ' ').trim();
    return `| ${node.name} | ${TYPE_LABEL[node.type] ?? node.type} | ${target(node)} | ${flags || '-'} | ${note} |`;
  });

  sections.push([
    `## ${wf.name}`,
    '',
    wf.meta.description,
    '',
    `**${wf.nodes.length} nodes.** Import from \`n8n/workflows/${file}\`.`,
    '',
    '| Node | Type | Talks to | Reliability | Why it is there |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '**Connections**',
    '',
    '```',
    ...flow(wf),
    '```',
    ''
  ].join('\n'));
}

const doc = [
  '# 4. Node-by-node reference',
  '',
  '> Generated by `node scripts/docs-workflows.mjs` from `n8n/workflows/*.json`.',
  '> Do not edit by hand - change `n8n/src/*.mjs`, run `npm run build:n8n`, then regenerate.',
  '',
  'Every workflow here is importable as-is. Two credentials must exist in n8n before',
  'they run: an HTTP Header Auth credential named **Supabase Service Role** and one',
  'named **Anthropic API Key**. Everything else comes from environment variables -',
  'see `.env.example` and `docs/05-integrations.md`.',
  '',
  '---',
  '',
  ...sections
].join('\n');

writeFileSync(join(ROOT, 'docs/04-node-by-node.md'), doc);
console.log(`docs/04-node-by-node.md written (${files.length} workflows, ${doc.split('\n').length} lines)`);
